# ===== 配置 =====
DATA_DIR = os.path.join(os.environ.get('APPDATA', os.path.expanduser('~')), 'hi-story', 'data')
DB_PATH = os.path.join(DATA_DIR, 'literary.db')

os.makedirs(DATA_DIR, exist_ok=True)

def log(msg):
    print(f"  [{datetime.now().strftime('%H:%M:%S')}] {msg}")

# ===== 数据库初始化 =====
def init_db():
    db = sqlite3.connect(DB_PATH)
    db.execute("PRAGMA journal_mode=WAL")
    db.execute("PRAGMA synchronous=OFF")

    # materials table
    db.execute("""
        CREATE TABLE IF NOT EXISTS materials (
            id TEXT PRIMARY KEY,
            project_id TEXT,
            source_layer TEXT NOT NULL,
            title TEXT NOT NULL,
            content TEXT NOT NULL DEFAULT '',
            url TEXT,
            tags TEXT NOT NULL DEFAULT '[]',
            created_at TEXT NOT NULL
        )
    """)

    # FTS5 tables per layer
    for layer in ['public_domain', 'history_military', 'myth_fantasy', 'dictionary', 'user']:
        db.execute(f"""
            CREATE VIRTUAL TABLE IF NOT EXISTS fts_{layer} USING fts5(
                title, content, source, tags, tokenize='unicode61'
            )
        """)

    return db

# ===== 下载辅助 =====
def download(url, retries=3):
    """下载文件，返回 bytes"""
    for i in range(retries):
        try:
            log(f"下载: {url[:80]}...")
            req = urllib.request.Request(url, headers={'User-Agent': 'hi-story/0.1.0'})
            with urllib.request.urlopen(req, timeout=30) as resp:
                return resp.read()
        except Exception as e:
            log(f"  ⚠ 重试 {i+1}/{retries}: {e}")
            time.sleep(2)
    raise Exception(f"下载失败: {url}")

# ===== 索引辅助 =====
def index_material(db, material_id, layer, title, content, source='', tags='[]'):
    """将素材插入 FTS 索引"""
    try:
        # 获取 materials 表的 rowid
        row = db.execute("SELECT rowid FROM materials WHERE id = ?", (material_id,)).fetchone()
        if not row:
            return
        rowid = row[0]
        db.execute(
            f"INSERT OR REPLACE INTO fts_{layer} (rowid, title, content, source, tags) VALUES (?, ?, ?, ?, ?)",
            (rowid, title, content, source, tags)
        )
    except Exception as e:
        pass  # FTS table may not exist yet

