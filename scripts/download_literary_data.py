# Layer 4: 词典修辞层 — 成语词典
# ====================================================================
def download_chengyu(db):
    """下载成语词典 (来源: GitHub pwxcoo/chinese-chengyu)"""
    log("📖 下载成语词典...")

    url = "https://raw.githubusercontent.com/pwxcoo/chinese-chengyu/master/database/data/chengyu.json"
    try:
        data = json.loads(download(url))
    except:
        log("⚠ GitHub 无法访问，使用备用数据...")
        return build_fallback_chengyu(db)

    count = 0
    for entry in data:
        cid = entry.get('id', f"chengyu_{count}")
        word = entry.get('word', '')
        pinyin = entry.get('pinyin', '')
        meaning = entry.get('explanation', '')
        source = entry.get('derivation', '')
        example = entry.get('example', '')

        if not word:
            continue

        content = f"【{word}】{pinyin}\n\n释义：{meaning}\n出处：{source}\n例句：{example}"
        tags = json.dumps(['成语', '词典'])

        mid = f"dict-chengyu-{cid}"
        db.execute(
            "INSERT OR IGNORE INTO materials (id, source_layer, title, content, url, tags, created_at) VALUES (?, 'dictionary', ?, ?, '', ?, ?)",
            (mid, word, content, tags, datetime.now().isoformat())
        )
        index_material(db, mid, 'dictionary', word, content)
        count += 1
        if count % 1000 == 0:
            log(f"  已导入 {count} 条成语...")
            db.commit()

    db.commit()
    log(f"✅ 成语词典: {count} 条")
    return count

